// Writes Sources/FRUSRichText/RTFCodePageTables.swift (S15d) from two dumps of dump.swift: the
// Mac's, CFString's decoding, which AppKit's RTF reader matched for every entry, and Linux's, from
// swift:6.4-noble's Foundation, which the codec calls for each pair the table leaves to it.
// tools/rtf-code-pages/make runs it.
//   generate <Mac dump> <Linux dump> <output file>

import Foundation

/// A dump: each page's entries, by their bytes in hexadecimal, as scalars joined by "+", or "-".
func readDump(_ path: String) throws -> [String: [String: String]] {
    var pages: [String: [String: String]] = [:]
    for line in try String(contentsOfFile: path, encoding: .utf8).split(separator: "\n") {
        let fields = line.split(separator: " ").map(String.init)
        guard fields.count == 3 else { throw GenerateError("\(path): a line is not page, bytes and scalars: \(line)") }
        pages[fields[0], default: [:]][fields[1]] = fields[2]
    }
    return pages
}

struct GenerateError: Error, CustomStringConvertible {
    let description: String
    init(_ description: String) { self.description = description }
}

/// Consecutive values as ranges, each its first and last.
func ranges(_ values: [Int]) -> [(Int, Int)] {
    var out: [(Int, Int)] = []
    for value in values {
        if let last = out.last, value == last.1 + 1 { out[out.count - 1].1 = value } else { out.append((value, value)) }
    }
    return out
}

func hex(_ value: Int, _ digits: Int) -> String {
    let text = String(value, radix: 16, uppercase: true)
    return "0x" + String(repeating: "0", count: max(0, digits - text.count)) + text
}

let singleBytePages = [
    ("cp1252", "Windows-1252, the code page of \\ansi and of a font in \\fcharset0"),
    ("cp1250", "Windows-1250, central European (\\fcharset238)"),
    ("cp1251", "Windows-1251, Cyrillic (\\fcharset204)"),
    ("cp1253", "Windows-1253, Greek (\\fcharset161)"),
    ("cp1254", "Windows-1254, Turkish (\\fcharset162)"),
    ("cp1255", "Windows-1255, Hebrew (\\fcharset177)"),
    ("cp1256", "Windows-1256, Arabic (\\fcharset178)"),
    ("cp1257", "Windows-1257, Baltic (\\fcharset186)"),
    ("cp1258", "Windows-1258, Vietnamese (\\fcharset163)"),
    ("cp874", "Windows-874, Thai (\\fcharset222)"),
    ("macRoman", "Mac OS Roman, the code page of \\mac and of a font in \\fcharset77"),
    ("nextstep", "NeXTSTEP, the code page of a document that names none, and of \\pc and \\pca"),
]
let doubleBytePages = [
    ("cp932", 0x0420, "Code page 932, Japanese (\\fcharset128)"),
    ("cp949", 0x0422, "Code page 949, Korean (\\fcharset129)"),
    ("cp936", 0x0421, "Code page 936, simplified Chinese (\\fcharset134)"),
    ("cp950", 0x0423, "Code page 950, traditional Chinese (\\fcharset136)"),
]

let header = """
    // Generated by tools/rtf-code-pages/make: the code pages AppKit's RTF reader decodes text bytes in
    // (S15d). Each table is the Mac's CFString decoding, which AppKit's reader matched for every byte
    // and every lead and trail pair of every charset here, on macOS 27.0.1 (probe of 24 Oct 2026, each
    // entry read in a group of its own). A single-byte table gives each byte from 0x80 its UTF-16 unit,
    // or 0 for one the code page does not define, which AppKit drops with the text it reads with it. A
    // double-byte table gives its lead bytes, the bytes that are characters by themselves, the pairs it
    // does not define and the pairs whose reading Foundation on Linux (swift:6.4-noble) does not give,
    // and leaves every other pair to Foundation, which reads them as the Mac does. The golden spans'
    // code pages hold the codec to AppKit's reading of every entry on CI, so a change to Linux's
    // Foundation fails there, until make writes this file again.

    extension RTFCodePage {
    """

func generate(mac: [String: [String: String]], linux: [String: [String: String]]) throws -> String {
    var lines = [header]
    func entries(_ page: String) throws -> [String: String] {
        guard let entries = mac[page] else { throw GenerateError("the Mac's dump has no \(page)") }
        return entries
    }
    for (name, doc) in singleBytePages {
        let page = try entries(name)
        lines.append("    /// \(doc).")
        lines.append("    static let \(name): [UInt16] = [")
        for row in 0..<8 {
            let cells = try (0..<16).map { column -> String in
                let key = String(format: "%02X", 0x80 + row * 16 + column)
                guard let value = page[key] else { throw GenerateError("\(name) has no byte \(key)") }
                return value == "-" ? "0" : hex(Int(value, radix: 16)!, 4)
            }
            lines.append("        " + cells.joined(separator: ", ") + ",")
        }
        lines.append("    ]")
        lines.append("")
    }
    for (index, (name, encoding, doc)) in doubleBytePages.enumerated() {
        let page = try entries(name)
        let singles = page.filter { $0.key.count == 2 }.reduce(into: [Int: String]()) { $0[Int($1.key, radix: 16)!] = $1.value }
        let pairs = page.filter { $0.key.count == 4 }.reduce(into: [Int: String]()) { $0[Int($1.key, radix: 16)!] = $1.value }
        let leads = Set(pairs.filter { $0.value != "-" }.map { $0.key >> 8 }).sorted()
        guard leads.allSatisfy({ singles[$0] == "-" }) else { throw GenerateError("\(name): a lead byte is a character by itself") }
        let characters = singles.filter { $0.value != "-" }
        guard characters.values.allSatisfy({ !$0.contains("+") }) else { throw GenerateError("\(name): a byte reads as two scalars") }
        let undefined = pairs.filter { $0.value == "-" && leads.contains($0.key >> 8) }.map(\.key).sorted()
        let overrides = try pairs.filter { $0.value != "-" && leads.contains($0.key >> 8) }.sorted { $0.key < $1.key }
            .filter { pair in
                guard let theirs = linux[name]?[String(format: "%04X", pair.key)] else { throw GenerateError("Linux's dump has no \(name) \(pair.key)") }
                return theirs != pair.value
            }
        lines.append("    /// \(doc).")
        lines.append("    static let \(name) = RTFDoubleByteTable(")
        lines.append("        encoding: \(hex(encoding, 4)),")
        lines.append("        leads: [" + ranges(leads).map { "\(hex($0.0, 2))...\(hex($0.1, 2))" }.joined(separator: ", ") + "],")
        // Single characters as a run each with its first unit, when consecutive bytes are consecutive units.
        let runs = try ranges(characters.keys.sorted()).map { first, last -> String in
            let base = Int(characters[first]!, radix: 16)!
            guard (first...last).allSatisfy({ Int(characters[$0]!, radix: 16)! == base + $0 - first }) else {
                throw GenerateError("\(name): bytes \(first)...\(last) are not consecutive units")
            }
            return "(\(hex(first, 2))...\(hex(last, 2)), \(hex(base, 4)))"
        }
        lines.append("        singles: [" + runs.joined(separator: ", ") + "],")
        lines.append("        undefined: [")
        let undefinedRanges = ranges(undefined)
        for start in stride(from: 0, to: undefinedRanges.count, by: 6) {
            let row = undefinedRanges[start..<min(start + 6, undefinedRanges.count)]
            lines.append("            " + row.map { "\(hex($0.0, 4)), \(hex($0.1, 4))" }.joined(separator: ", ") + ",")
        }
        lines.append("        ],")
        if overrides.isEmpty {
            lines.append("        overrides: [:]")
        } else {
            lines.append("        overrides: [")
            for start in stride(from: 0, to: overrides.count, by: 4) {
                let row = overrides[start..<min(start + 4, overrides.count)].map { pair in
                    "\(hex(pair.key, 4)): [" + pair.value.split(separator: "+").map { hex(Int($0, radix: 16)!, 4) }.joined(separator: ", ") + "]"
                }
                lines.append("            " + row.joined(separator: ", ") + ",")
            }
            lines.append("        ]")
        }
        lines.append("    )")
        if index < doubleBytePages.count - 1 { lines.append("") }
        FileHandle.standardError.write(Data("\(name): \(leads.count) leads, \(undefinedRanges.count) undefined ranges, \(overrides.count) overrides\n".utf8))
    }
    lines.append("}")
    return lines.joined(separator: "\n") + "\n"
}

let arguments = CommandLine.arguments
guard arguments.count == 4 else {
    FileHandle.standardError.write(Data("usage: generate <Mac dump> <Linux dump> <output file>\n".utf8))
    exit(2)
}
do {
    let source = try generate(mac: try readDump(arguments[1]), linux: try readDump(arguments[2]))
    try source.write(toFile: arguments[3], atomically: true, encoding: .utf8)
} catch {
    FileHandle.standardError.write(Data("generate: \(error)\n".utf8))
    exit(1)
}
