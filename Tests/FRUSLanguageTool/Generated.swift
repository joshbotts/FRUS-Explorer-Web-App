// The two files FRUSLanguage compiles its model and lists from: Swift sources holding each as a raw
// string literal, with its length or digest and its provenance, so that the server's binary carries them.

import FRUSLanguage
import Foundation

enum Generated {
    /// Writes `EmbeddedModel.swift`: the model's file in base64, a hundred characters a line, with its
    /// length, SHA-256 and provenance.
    static func writeModel(bytes: [UInt8], provenance: String, to url: URL) throws {
        let base64 = Data(bytes).base64EncodedString()
        var lines: [Substring] = []
        var start = base64.startIndex
        while start < base64.endIndex {
            let end = base64.index(start, offsetBy: 100, limitedBy: base64.endIndex) ?? base64.endIndex
            lines.append(base64[start..<end])
            start = end
        }
        let source = """
            // Generated by frus-language train (PLAN's S29c): the lexical-class tagger's model, an averaged perceptron
            // with integer weights, in base64. Do not edit: train again, as DEVLOG's Session 29c says. Its provenance
            // below names the text it was trained from and that text's licence.

            enum EmbeddedModel {
                static let byteCount = \(bytes.count)
                static let sha256 = "\(LanguageTagger.sha256(bytes))"
                static let provenance = #\"\"\"
            \(provenance)
            \"\"\"#
                static let base64: StaticString = #\"\"\"
            \(lines.joined(separator: "\n"))
            \"\"\"#
            }

            """
        try Data(source.utf8).write(to: url, options: .atomic)
    }

    /// Writes `EmbeddedWordNet.swift`: the lists' canonical text, with its SHA-256, its provenance and
    /// WordNet's licence, read from its distribution's LICENSE file, which goes with every copy of WordNet's database.
    static func writeWordNet(text: String, source: String, licence: String, lists: [WordNetPart: WordNetPartLists], to url: URL) throws {
        // The licence as WordNet's distribution words it, every line kept, as a comment.
        let licenceComment = licence.split(separator: "\n", omittingEmptySubsequences: false)
            .map { line -> String in
                let trimmed = line.reversed().drop(while: { $0 == " " || $0 == "\t" || $0 == "\r" }).reversed()
                return trimmed.isEmpty ? "//" : "// " + String(trimmed)
            }
            .joined(separator: "\n")
            .trimmingCharacters(in: .whitespacesAndNewlines)
        let counts = WordNetPart.allCases.map { part in
            "\(part.rawValue) \(lists[part]?.exceptions.count ?? 0) exceptions and \(lists[part]?.lemmas.count ?? 0) lemmas"
        }.joined(separator: ", ")
        let generated = """
            // Generated by frus-language wordnet (PLAN's S29c): WordNet's exception lists and the single words of its
            // indexes, which the lemmatizer reads, in the canonical text WordNetLists describes. Do not edit: read
            // WordNet's files again, as DEVLOG's Session 29c says.
            //
            // \(source)
            // \(counts).
            //
            \(licenceComment)

            enum EmbeddedWordNet {
                static let sha256 = "\(LanguageTagger.sha256(Array(text.utf8)))"
                static let provenance = #\"\"\"
            \(source)
            \"\"\"#
                static let lists: StaticString = #\"\"\"
            \(text)
            \"\"\"#
            }

            """
        try Data(generated.utf8).write(to: url, options: .atomic)
    }
}
